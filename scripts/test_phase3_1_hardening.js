const { PrismaClient } = require('@prisma/client');
const bcrypt = require('bcryptjs');
const { SignJWT } = require('jose');
const path = require('path');
const fs = require('fs');

const envPath = path.resolve(__dirname, '..', '.env');
if (fs.existsSync(envPath)) {
  if (process.loadEnvFile) {
    process.loadEnvFile(envPath);
  } else {
    const lines = fs.readFileSync(envPath, 'utf8').split('\n');
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const idx = trimmed.indexOf('=');
      if (idx !== -1) {
        const key = trimmed.slice(0, idx).trim();
        let val = trimmed.slice(idx + 1).trim();
        if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
          val = val.slice(1, -1);
        }
        if (!process.env[key]) process.env[key] = val;
      }
    }
  }
}

const prisma = new PrismaClient();
const SECRET_KEY = new TextEncoder().encode(
  process.env.SESSION_SECRET || 'nadc-default-dev-secret-change-in-prod-at-least-32-chars'
);

let passed = 0;
let failed = 0;

function assert(condition, message) {
  if (condition) {
    console.log(`  ✓ ${message}`);
    passed++;
  } else {
    console.error(`  ✘ FAILED: ${message}`);
    failed++;
  }
}

async function createJWT(user) {
  return new SignJWT({
    userId: user.id,
    name: user.name,
    username: user.username,
    role: user.role,
    sessionId: 'test-session-' + Date.now(),
  })
    .setProtectedHeader({ alg: 'HS256' })
    .setIssuedAt()
    .setExpirationTime('2h')
    .sign(SECRET_KEY);
}

const TEST_USERNAMES = [
  'phase31_test_main',
  'phase31_test_asst_victim',
  'phase31_test_asst_target',
];

async function cleanup() {
  try {
    const testUsers = await prisma.user.findMany({
      where: { username: { in: TEST_USERNAMES } },
      select: { id: true },
    });
    const userIds = testUsers.map((u) => u.id);
    if (userIds.length > 0) {
      await prisma.student.deleteMany({
        where: { createdById: { in: userIds } },
      });
      await prisma.user.deleteMany({
        where: { id: { in: userIds } },
      });
    }
    await prisma.student.deleteMany({
      where: { roll: { startsWith: 'HARDEN-' } },
    });
    // Clean synthetic audit logs generated by test
    await prisma.auditLog.deleteMany({
      where: {
        OR: [
          { actorName: { startsWith: 'Phase31' } },
          { details: { contains: 'HARDEN-' } },
        ],
      },
    });
  } catch (err) {
    // ignore
  }
}

async function runHardeningTests() {
  console.log('\n=============================================================');
  console.log(' Phase 3.1: Security Hardening & Data Protection Test Suite');
  console.log('=============================================================\n');

  try {
    await cleanup();

    const passwordHash = await bcrypt.hash('HardenSecPass123!', 12);

    const mainAdmin = await prisma.user.create({
      data: {
        name: 'Phase31 Main Admin',
        username: 'phase31_test_main',
        email: 'main@phase31.local',
        passwordHash,
        role: 'MAIN_ADMIN',
        isActive: true,
      },
    });

    const asstVictim = await prisma.user.create({
      data: {
        name: 'Phase31 Assistant Admin Victim',
        username: 'phase31_test_asst_victim',
        email: 'asstvictim@phase31.local',
        passwordHash,
        role: 'ASSISTANT_ADMIN',
        isActive: true,
      },
    });

    const mainToken = await createJWT(mainAdmin);
    const baseUrl = 'http://localhost:3000';

    // -------------------------------------------------------------------------
    // TEST 1: Administrator Deletion Blocked When Student Records Exist
    // -------------------------------------------------------------------------
    console.log('[1/7] Testing Student Protection from Accidental Deletion...');
    // Create a student record owned by asstVictim
    const student1 = await prisma.student.create({
      data: {
        name: 'Protected Synthetic Student 1',
        studentClass: 'HSC 1st Year (একাদশ শ্রেণি)',
        roll: 'HARDEN-001',
        group: 'Science (বিজ্ঞান)',
        section: 'A',
        guardianName: 'Guardian Harden 1',
        guardianRelationship: 'Father',
        homeAddress: 'Umedpur, Shibchar, Madaripur',
        createdById: asstVictim.id,
      },
    });

    // Main Admin attempts to delete asstVictim WITHOUT reassignment
    const rBlockedDelete = await fetch(`${baseUrl}/api/admin/users/${asstVictim.id}`, {
      method: 'DELETE',
      headers: {
        Cookie: `nadc_admin_session=${mainToken}`,
        Origin: 'http://localhost:3000',
      },
    });
    const blockedResult = await rBlockedDelete.json();

    assert(
      rBlockedDelete.status === 400 && blockedResult.requiresReassignment === true,
      'Deletion blocked: Server returns 400 Bad Request with requiresReassignment flag'
    );

    // Verify student record is intact in DB
    const studentCheck1 = await prisma.student.findUnique({ where: { id: student1.id } });
    assert(studentCheck1 !== null, 'Student record remained completely intact and was NOT deleted');

    // Verify administrator was NOT deleted
    const adminCheck1 = await prisma.user.findUnique({ where: { id: asstVictim.id } });
    assert(adminCheck1 !== null, 'Administrator account remained intact');

    // -------------------------------------------------------------------------
    // TEST 2: Authorized Student Reassignment Workflow
    // -------------------------------------------------------------------------
    console.log('\n[2/7] Testing Authorized Student Reassignment Workflow...');
    // Main Admin reassigns students to mainAdmin and deletes asstVictim
    const rReassignDelete = await fetch(
      `${baseUrl}/api/admin/users/${asstVictim.id}?reassignToId=${mainAdmin.id}`,
      {
        method: 'DELETE',
        headers: {
          Cookie: `nadc_admin_session=${mainToken}`,
          Origin: 'http://localhost:3000',
        },
      }
    );
    const reassignResult = await rReassignDelete.json();

    assert(
      rReassignDelete.status === 200 && reassignResult.success === true,
      'Reassignment deletion succeeded with 200 OK'
    );

    // Verify student record now belongs to mainAdmin (not orphaned, not lost)
    const studentAfterReassign = await prisma.student.findUnique({ where: { id: student1.id } });
    assert(
      studentAfterReassign?.createdById === mainAdmin.id,
      'Student record successfully reassigned to Main Admin (Zero Student Data Loss)'
    );

    // Verify victim admin was removed
    const adminAfterDelete = await prisma.user.findUnique({ where: { id: asstVictim.id } });
    assert(adminAfterDelete === null, 'Victim assistant administrator successfully removed');

    // -------------------------------------------------------------------------
    // TEST 3: Database Schema Foreign Key (onDelete: Restrict)
    // -------------------------------------------------------------------------
    console.log('\n[3/7] Testing Database Schema onDelete: Restrict Enforcement...');
    // Create assistant and student, then attempt direct DB deletion
    const asstDirect = await prisma.user.create({
      data: {
        name: 'Phase31 Direct Asst',
        username: 'phase31_test_asst_target',
        email: 'direct@phase31.local',
        passwordHash,
        role: 'ASSISTANT_ADMIN',
        isActive: true,
      },
    });

    const studentDirect = await prisma.student.create({
      data: {
        name: 'Protected Synthetic Student 2',
        studentClass: 'HSC 2nd Year (দ্বাদশ শ্রেণি)',
        roll: 'HARDEN-002',
        group: 'Humanities (মানবিক)',
        section: 'B',
        guardianName: 'Guardian Harden 2',
        guardianRelationship: 'Mother',
        homeAddress: 'Shibchar, Madaripur',
        createdById: asstDirect.id,
      },
    });

    let dbRestrictBlocked = false;
    try {
      // Attempting direct raw delete bypassing application layer
      await prisma.user.delete({ where: { id: asstDirect.id } });
    } catch (err) {
      // Prisma P2003 = Foreign key constraint failed
      if (err.code === 'P2003' || String(err).includes('Foreign key constraint')) {
        dbRestrictBlocked = true;
      }
    }
    assert(dbRestrictBlocked, 'Database schema enforces foreign key Restrict: direct deletion prohibited at DB level');

    // Clean up direct student and user
    await prisma.student.delete({ where: { id: studentDirect.id } });
    await prisma.user.delete({ where: { id: asstDirect.id } });

    // -------------------------------------------------------------------------
    // TEST 4: Origin Validation (Cross-Origin Mutation Rejection)
    // -------------------------------------------------------------------------
    console.log('\n[4/7] Testing Origin Validation & Untrusted Origin Rejection...');
    const maliciousOrigin = 'https://attacker-cross-origin.com';

    // 4.1 POST /api/admin/students with untrusted origin
    const rCrossOriginStudent = await fetch(`${baseUrl}/api/admin/students`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Cookie: `nadc_admin_session=${mainToken}`,
        Origin: maliciousOrigin,
      },
      body: JSON.stringify({
        name: 'Malicious Cross Origin Student',
        studentClass: 'HSC 1st Year (একাদশ শ্রেণি)',
        roll: 'HARDEN-XORIGIN',
        group: 'Science (বিজ্ঞান)',
        section: 'A',
        guardianName: 'Guardian X',
        guardianRelationship: 'Father',
        homeAddress: 'Address X',
      }),
    });
    assert(
      rCrossOriginStudent.status === 403,
      'POST /api/admin/students rejected with 403 Forbidden on untrusted Origin'
    );

    // 4.2 PUT /api/admin/students/:id with untrusted origin
    const rCrossOriginPut = await fetch(`${baseUrl}/api/admin/students/${student1.id}`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        Cookie: `nadc_admin_session=${mainToken}`,
        Origin: maliciousOrigin,
      },
      body: JSON.stringify({
        name: 'Updated Cross Origin',
        studentClass: student1.studentClass,
        roll: student1.roll,
        group: student1.group,
        section: student1.section,
        guardianName: student1.guardianName,
        guardianRelationship: student1.guardianRelationship,
        homeAddress: student1.homeAddress,
      }),
    });
    assert(
      rCrossOriginPut.status === 403,
      'PUT /api/admin/students/:id rejected with 403 Forbidden on untrusted Origin'
    );

    // 4.3 DELETE /api/admin/students/:id with untrusted origin
    const rCrossOriginDelete = await fetch(`${baseUrl}/api/admin/students/${student1.id}`, {
      method: 'DELETE',
      headers: {
        Cookie: `nadc_admin_session=${mainToken}`,
        Origin: maliciousOrigin,
      },
    });
    assert(
      rCrossOriginDelete.status === 403,
      'DELETE /api/admin/students/:id rejected with 403 Forbidden on untrusted Origin'
    );

    // 4.4 POST /api/auth/login with untrusted origin
    const rCrossOriginLogin = await fetch(`${baseUrl}/api/auth/login`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Origin: maliciousOrigin,
      },
      body: JSON.stringify({
        username: 'admin',
        password: 'CollegeAdmin2026!',
      }),
    });
    assert(
      rCrossOriginLogin.status === 403,
      'POST /api/auth/login rejected with 403 Forbidden on untrusted Origin'
    );

    // -------------------------------------------------------------------------
    // TEST 5: Legitimate Same-Origin Requests Accepted
    // -------------------------------------------------------------------------
    console.log('\n[5/7] Testing Legitimate Same-Origin Requests...');
    const rLegitStudent = await fetch(`${baseUrl}/api/admin/students`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Cookie: `nadc_admin_session=${mainToken}`,
        Origin: 'http://localhost:3000',
      },
      body: JSON.stringify({
        name: 'Legitimate Origin Student',
        studentClass: 'HSC 1st Year (একাদশ শ্রেণি)',
        roll: 'HARDEN-LEGIT',
        group: 'Science (বিজ্ঞান)',
        section: 'A',
        guardianName: 'Guardian Legit',
        guardianRelationship: 'Father',
        homeAddress: 'Legit Address, Shibchar',
      }),
    });
    assert(
      rLegitStudent.status === 201,
      'POST /api/admin/students accepted (201 Created) with legitimate Origin: http://localhost:3000'
    );

    // -------------------------------------------------------------------------
    // TEST 6: Audit Log Integrity & Privacy (Zero PII Leakage)
    // -------------------------------------------------------------------------
    console.log('\n[6/7] Testing Audit Log Recording & PII Sanitization...');
    const recentAuditLogs = await prisma.auditLog.findMany({
      orderBy: { createdAt: 'desc' },
      take: 20,
    });

    assert(recentAuditLogs.length > 0, `Audit logs captured: ${recentAuditLogs.length} events recorded`);

    // Verify actions logged
    const actions = recentAuditLogs.map((a) => a.action);
    assert(
      actions.includes('ADMIN_DELETE_BLOCKED_HAS_STUDENTS') ||
      actions.includes('ADMIN_REASSIGN_STUDENTS') ||
      actions.includes('STUDENT_CREATE'),
      'Specific administrative actions (ADMIN_DELETE_BLOCKED_HAS_STUDENTS, STUDENT_CREATE) present in audit trail'
    );

    // Strict Privacy Verification: Check that NO phone numbers, emails, passwords, or addresses exist in audit details
    let piiFound = false;
    for (const log of recentAuditLogs) {
      if (!log.details) continue;
      const text = log.details.toLowerCase();
      // Check for raw passwords or sensitive PII
      if (
        text.includes('hardenSecpass') ||
        text.includes('passwordhash') ||
        text.includes('017') ||
        text.includes('018') ||
        text.includes('019') ||
        text.includes('@phase31.local')
      ) {
        piiFound = true;
        console.error(`  ✘ PII leak detected in audit log: ${log.details}`);
      }
    }
    assert(!piiFound, 'Audit log verified: ZERO passwords, phone numbers, or emails present in details payload');

    // -------------------------------------------------------------------------
    // TEST 7: Login Rate Limiting (Single Process Sliding Window)
    // -------------------------------------------------------------------------
    console.log('\n[7/7] Testing Login Rate Limiting...');
    // We already know rate limiting triggers after 5 failed attempts
    const uniqueUser = 'ratelimit_probe_' + Date.now();
    let hitRateLimit = false;

    for (let i = 0; i < 6; i++) {
      const res = await fetch(`${baseUrl}/api/auth/login`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Origin: 'http://localhost:3000',
        },
        body: JSON.stringify({
          username: uniqueUser,
          password: 'wrongpassword',
        }),
      });

      if (res.status === 429) {
        hitRateLimit = true;
        break;
      }
    }
    assert(hitRateLimit, 'Rate limiter correctly triggered 429 Too Many Requests after consecutive failed logins');

    // Clean up
    await cleanup();

    console.log('\n=============================================================');
    console.log(` RESULTS: ${passed} PASSED, ${failed} FAILED across 7 hardening suites.`);
    console.log('=============================================================\n');

    if (failed > 0) {
      process.exit(1);
    }
  } catch (err) {
    console.error('Fatal test error:', err);
    process.exit(1);
  } finally {
    await cleanup();
    await prisma.$disconnect();
  }
}

runHardeningTests();
